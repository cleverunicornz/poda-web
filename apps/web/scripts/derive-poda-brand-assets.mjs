const unsafeSvg =
    /<script|<foreignObject|<image\b|<iframe|<audio|<video|<!DOCTYPE|<!ENTITY|\son[a-z]+\s*=|@import|data:|(?:xlink:href|href)=["'](?!#)|url\((?!#)/iu;

function sha256(content) {
    return createHash("sha256").update(content).digest("hex");
}

function countVisibleElements(svg, elementName) {
    return [...svg.matchAll(new RegExp(`<${elementName}(?:\\s|>)`, "giu"))].length;
}

function sanitizeSvg(source, sourceName, sourceDigest) {
    if (unsafeSvg.test(source)) {
        throw new Error(`${sourceName} contains disallowed executable or external SVG content`);
    }

    const sourceViewBox = source.match(/\bviewBox="([^"]+)"/u)?.[1];
    if (!sourceViewBox) throw new Error(`${sourceName} has no viewBox`);

    let output = source
        .replace(/<\?xml[^>]*>\s*/gu, "")
        .replace(/<!--\s*Created with Inkscape[^>]*-->\s*/giu, "")
        .replace(/<sodipodi:namedview\b[\s\S]*?\/>/giu, "")
        .replace(/<inkscape:path-effect\b[\s\S]*?\/>/giu, "")
        .replace(/\bxlink:href=/gu, "href=")
        .replace(/\s+(?:inkscape|sodipodi):[a-z0-9_-]+="[^"]*"/giu, "")
        .replace(/\s+xmlns:(?:inkscape|sodipodi|xlink|svg)="[^"]*"/giu, "")
        .replace(/^\s+$/gmu, "")
        .trim();

    const provenance = `<!-- Generated by apps/web/scripts/derive-poda-brand-assets.mjs from ${sourceName} (${sourceDigest}). -->`;
    output = `${provenance}\n${output}\n`;

    if (/inkscape|sodipodi|xlink:/iu.test(output) || unsafeSvg.test(output)) {
        throw new Error(`${sourceName} was not fully sanitized`);
    }
    if (output.match(/\bviewBox="([^"]+)"/u)?.[1] !== sourceViewBox) {
        throw new Error(`${sourceName} changed viewBox during sanitization`);
    }

    for (const elementName of ["path", "ellipse", "circle", "rect", "polygon", "polyline", "line"]) {
        if (countVisibleElements(source, elementName) !== countVisibleElements(output, elementName)) {
            throw new Error(`${sourceName} changed visible <${elementName}> element count`);
        }
    }

    return Buffer.from(output, "utf8");
}

let failed = false;
for (const asset of assets) {
    const sourcePath = path.join(sourceDirectory, asset.source);
    const outputPath = path.join(outputDirectory, asset.output);
    const source = readFileSync(sourcePath);
    const actualSourceDigest = sha256(source);
    if (actualSourceDigest !== asset.sourceSha256) {
        throw new Error(`${asset.source} digest ${actualSourceDigest} does not match the admitted source digest`);
    }

    const expected =
        asset.kind === "svg" ? sanitizeSvg(source.toString("utf8"), asset.source, asset.sourceSha256) : source;

    if (checkOnly) {
        let actual;
        try {
            actual = readFileSync(outputPath);
        } catch {
            console.error(`missing ${asset.output}`);
            failed = true;
            continue;
        }
        if (!actual.equals(expected)) {
            console.error(`stale ${asset.output}`);
            failed = true;
            continue;
        }
    } else {
        mkdirSync(path.dirname(outputPath), { recursive: true });
        writeFileSync(outputPath, expected);
    }

    console.log(`${checkOnly ? "verified" : "generated"} ${asset.output} ${sha256(expected)}`);
}

if (failed) process.exitCode = 1;
